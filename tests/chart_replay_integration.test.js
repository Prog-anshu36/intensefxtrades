const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
let local = false;
const sandbox = { window: {}, Date, Math, MarketData: { isLocal: () => local } };
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync('frontend/static/js/page_backtesting.js', 'utf8'), sandbox);
const page = sandbox.window.PageBacktesting;
page.candles = Array.from({ length: 5 }, (_, i) => ({ time: i * 60000, date: new Date(i * 60000) }));
page.replayActive = true; page.idx = 0; page.autoFollow = false;
page.dataSource = 'local-csv'; page.datasetInfo = { last_timestamp: 240000 };
const evaluated = [];
let stopped = 0, loads = 0;
for (const method of ['syncReplayTimestamp','syncReplayBuffers','updateReplayChrome','scheduleDraw','emitReplayEvent','persistReplayState','startRevealAnimation']) page[method] = () => {};
page.evaluateCandle = async () => { evaluated.push(page.idx); };
page.stopPlay = () => { stopped++; };
page.loadLocalPage = async () => { loads++; };
(async () => {
  await page.step(3);
  assert.deepEqual(evaluated, [1, 2, 3], 'fast forward evaluates every candle for pending orders and SL/TP');
  assert.equal(page.idx, 3);
  evaluated.length = 0; page.idx = 0; local = true;
  await page.step(3);
  assert.deepEqual(evaluated, [1, 2, 3], 'CSV replay has the same chronological execution');
  await page.step(3);
  assert.equal(page.idx, 4);
  assert.equal(page.candles.length, 5, 'dataset end never fabricates candles');
  assert.ok(stopped > 0); assert.equal(loads, 1);
  page._placingOrder = true;
  await page.step(-1);
  assert.equal(page.idx, 4, 'order submission holds the replay price until completed');
  page._placingOrder = false;
  assert.equal(page._stepping, false, 'step lock is released');
  console.log('chart_replay_integration.test.js passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
